def videos_and_courses(skill: str) -> list[tuple[str, str]]:
    """[(title, url)], free first: a freeCodeCamp full course, a topic-specialist channel, Coursera
    (audit for free) and a web search for more free resources. YouTube and web links are searches,
    so they never point to a deleted or made-up video; the student opens them in a new tab."""
    from urllib.parse import quote_plus
    channel, query = VIDEOS.get(skill, ("YouTube", f"{skill} tutorial for beginners"))
    out = []
    if channel != "freeCodeCamp":
        out.append(("▶ freeCodeCamp full course (free)",
                    f"https://www.youtube.com/results?search_query={quote_plus(skill + ' full course freecodecamp')}"))
    out.append((f"▶ {channel}" + (" (free)" if channel == "freeCodeCamp" else ""),
                f"https://www.youtube.com/results?search_query={quote_plus(query)}"))
    title, url = COURSES.get(skill, (f"Coursera: {skill}", f"https://www.coursera.org/search?query={quote_plus(skill)}"))
    out.append((f"🎓 {title} (audit for free)", url))
    out.append(("🔎 More free resources", f"https://www.google.com/search?q={quote_plus('free ' + skill + ' course for beginners')}"))
    return out
